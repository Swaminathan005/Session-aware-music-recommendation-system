#!/usr/bin/env python3
"""
db_schema.py

Utility to print the schema of the three NoSQL stores used in the project:
MongoDB, Redis, Cassandra.
"""

def print_schemas():
    lines = []
    lines.append("=" * 60)
    lines.append("MongoDB Collections")
    lines.append("=" * 60)
    lines.append("Collection: songs")
    lines.append("  _id: ObjectId (or custom song ID)")
    lines.append("  name: string")
    lines.append("  artist: string")
    lines.append("  album: string (optional)")
    lines.append("  genres: array of strings")
    lines.append("  year: integer (optional)")
    lines.append("  duration_ms: integer")
    lines.append("  audio_features: embedded document")
    lines.append("    - danceability: float [0,1]")
    lines.append("    - energy: float [0,1]")
    lines.append("    - instrumentalness: float [0,1]")
    lines.append("    - liveness: float [0,1]")
    lines.append("    - valence: float [0,1]")
    lines.append("    - tempo: float (BPM)")
    lines.append("    - key: integer (0-11)")
    lines.append("    - loudness: float (dB)")
    lines.append("    - mode: integer (0=minor,1=major)")
    lines.append("    - speechiness: float [0,1]")
    lines.append("    - acousticness: float [0,1]")
    lines.append("  source: string ('msd' | 'spotify')")
    lines.append("  created_at: ISODate")
    lines.append("  updated_at: ISODate")
    lines.append("")
    lines.append("=" * 60)
    lines.append("Redis Key Patterns")
    lines.append("=" * 60)
    lines.append("song_emb:<song_id> -> Hash")
    lines.append("  vec: binary blob (64-dim float vector) or base64 string")
    lines.append("  norm: float (pre‑computed L2 norm)")
    lines.append("  source: string ('msd'|'spotify')")
    lines.append("  updated_at: unix timestamp (ms)")
    lines.append("")
    lines.append("user_vec:<user_id> -> Hash")
    lines.append("  vec: binary blob")
    lines.append("  norm: float")
    lines.append("  updated_at: unix timestamp (ms)")
    lines.append("")
    lines.append("sess_vec:<session_id> -> Hash")
    lines.append("  vec: binary blob")
    lines.append("  norm: float")
    lines.append("  updated_at: unix timestamp (ms)")
    lines.append("")
    lines.append("sess_hist:<session_id> -> List")
    lines.append("  Elements: song_id strings (LPUSH for each new play)")
    lines.append("")
    lines.append("user_playcount:<user_id>:<song_id> -> Hash")
    lines.append("  count: integer (raw play count)")
    lines.append("")
    lines.append("top_n:<user_id>:<algo> -> Sorted Set")
    lines.append("  Score: recommendation score (float)")
    lines.append("  Member: song_id string")
    lines.append("")
    lines.append("lock:<resource> -> String")
    lines.append("  Used for short‑lived distributed locks (SET NX PX)")
    lines.append("")
    lines.append("=" * 60)
    lines.append("Cassandra Keyspace: music_rec")
    lines.append("=" * 60)
    lines.append("Table: user_listening_events")
    lines.append("  Partition key: user_id (uuid)")
    lines.append("  Clustering key: event_time (timeuuid) DESC")
    lines.append("  Columns:")
    lines.append("    song_id: text")
    lines.append("    session_id: text (optional)")
    lines.append("    context: text (e.g., 'home','work','travel')")
    lines.append("    track_name: text (denormalized for convenience)")
    lines.append("    artist_name: text")
    lines.append("    played_at: timestamp")
    lines.append("    ingested_at: timestamp (write time)")
    lines.append("")
    lines.append("Table: sessions")
    lines.append("  Partition key: session_id (text)")
    lines.append("  Columns:")
    lines.append("    user_id: uuid")
    lines.append("    start_time: timestamp")
    lines.append("    end_time: timestamp")
    lines.append("    track_ids: list<text>")
    lines.append("    event_count: int")
    lines.append("    context_tags: set<text>")
    lines.append("    vector_blob: blob (session vector at end)")
    lines.append("")
    lines.append("Table: user_vector")
    lines.append("  Partition key: user_id (uuid)")
    lines.append("  Columns:")
    lines.append("    vector_blob: blob (64‑dim float vector)")
    lines.append("    norm: float")
    lines.append("    updated_at: timestamp")
    lines.append("    version: int (incremented on each update)")
    lines.append("")
    lines.append("Table: song_vector")
    lines.append("  Partition key: song_id (text)")
    lines.append("  Columns:")
    lines.append("    vector_blob: blob")
    lines.append("    norm: float")
    lines.append("    source: text ('msd'|'spotify')")
    lines.append("    updated_at: timestamp")
    lines.append("")
    lines.append("Table: playcount_agg")
    lines.append("  Partition key: user_id (uuid)")
    lines.append("  Clustering key: song_id (text)")
    lines.append("  Columns:")
    lines.append("    play_count: counter")
    lines.append("    last_played: timestamp")
    lines.append("")
    lines.append("Table: daily_trends")
    lines.append("  Partition key: date (date)")
    lines.append("  Clustering key: genre (text)")
    lines.append("  Columns:")
    lines.append("    play_count: counter")
    lines.append("    unique_users: counter")
    lines.append("    top_song_ids: list<text> (top 10 songs for the day/genre)")
    lines.append("")
    lines.append("=" * 60)
    return "\n".join(lines)


if __name__ == "__main__":
    print(print_schemas())