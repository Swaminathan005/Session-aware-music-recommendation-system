def load_lightfm_embeddings() -> Tuple[np.ndarray, Dict[str, int], Dict[int, str]]:
    """
    Load song embeddings and ID↔index maps.
    Returns: embeddings matrix (n_songs, 64), id2idx, idx2id.
    """
    if not LIGHTFM_EMBEDDINGS_PATH.is_file():
        raise FileNotFoundError(f"Missing {LIGHTFM_EMBEDDINGS_PATH}")
    if not LIGHTFM_ID_MAP_PATH.is_file():
        raise FileNotFoundError(f"Missing {LIGHTFM_ID_MAP_PATH}")
    E = np.load(LIGHTFM_EMBEDDINGS_PATH)          # (n_songs, 64)
    with open(LIGHTFM_ID_MAP_PATH, 'rb') as f:
        id2idx = pickle.load(f)                   # dict: song_id -> index
    idx2id = {v: k for k, v in id2idx.items()}
    n = E.shape[0]
    if set(id2idx.values()) != set(range(n)):
        raise ValueError("id2idx values are not a permutation of 0..n-1")
    return E, id2idx, idx2id


