def get_user_play_counts(history: pd.DataFrame) -> Dict[str, float]:
    """
    Return dict mapping song ID (MSD or Spotify) to raw play count.
    Uses matched_msd_id if available, else spotify_id.
    """
    if history.empty:
        return {}
    # Determine which column to use as song ID
    if 'matched_msd_id' in history.columns:
        # Use MSD ID where available, else fall back to Spotify ID
        history['song_id'] = history['matched_msd_id'].fillna(history['spotify_id'])
    else:
        history['song_id'] = history['spotify_id']
    # Count plays per song
    raw_counts = history['song_id'].value_counts()
    return dict(raw_counts)


def get_long_term_user_vector(embeddings: np.ndarray,
                              id2idx: Dict[str, int],
                              play_counts: Dict[str, float]) -> np.ndarray:
    """
    Compute long-term preference vector U as a weighted average of song embeddings
    that the user has listened to, weighted by log1p play count.
    If no listening history, returns zero vector.
    """
    if not play_counts:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    # Gather vectors and weights for songs the user has played
    vecs = []
    weights = []
    for song_id, raw_count in play_counts.items():
        if song_id in id2idx:
            idx = id2idx[song_id]
            vecs.append(embeddings[idx])
            weights.append(np.log1p(raw_count))  # log1p weighting
    if not vecs:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    vecs = np.stack(vecs)          # (n_played, 64)
    weights = np.array(weights)    # (n_played,)
    # Weighted average
    u_vec = np.average(vecs, axis=0, weights=weights)
    return u_vec


def get_session_representation_via_word2vec(history: pd.DataFrame,
                                            embeddings: np.ndarray,
                                            id2idx: Dict[str, int]) -> np.ndarray:
    """
    Compute session representation S using Word2Vec Skip-Gram.
    For simplicity, if we don't have a trained Word2Vec model, we fall back to
    averaging the embeddings of the most recent songs (within a session window).
    In a full implementation, you would:
        1. Split history into sessions (e.g., gap > 30 min).
        2. For each session, train/infer Word2Vec to get session vector.
        3. Use the most recent session's vector.
    Here we implement a simple fallback: average of last N songs (N=20) embeddings.
    """
    if history.empty:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    # Ensure we have song IDs
    if 'matched_msd_id' in history.columns:
        history['song_id'] = history['matched_msd_id'].fillna(history['spotify_id'])
    else:
        history['song_id'] = history['spotify_id']
    # Take the most recent songs (up to 20) as the current session
    recent = history.sort_values('played_at', ascending=False).head(20)
    # Map to indices
    indices = []
    for sid in recent['song_id']:
        if sid in id2idx:
            indices.append(id2idx[sid])
    if not indices:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    sess_embeds = embeddings[indices]   # (n_recent, 64)
    # Simple average (could be weighted by recency)
    s_vec = np.mean(sess_embeds, axis=0)
    return s_vec


def combine_context(u_vec: np.ndarray, s_vec: np.ndarray) -> np.ndarray:
    """
    Combine long-term and session vectors: C = 0.4*U + 0.6*S
    """
    return LAMBDA_U * u_vec + LAMBDA_S * s_vec


