def get_candidate_songs(embeddings: np.ndarray,
                        context_vec: np.ndarray,
                        top_n: int = TOP_CANDIDATES) -> Tuple[np.ndarray, np.ndarray]:
    """
    Retrieve top_n candidate songs by cosine similarity to context_vec.
    Returns: (candidate_indices, candidate_vectors)
    For large catalogs, replace with FAISS approximate nearest neighbor search.
    """
    # Normalize context and embeddings
    context_norm = np.linalg.norm(context_vec)
    if context_norm == 0:
        # If context is zero, return arbitrary ordering (e.g., first top_n)
        cand_idx = np.arange(min(top_n, embeddings.shape[0]))
        return cand_idx, embeddings[cand_idx]
    context_unit = context_vec / context_norm
    norms = np.linalg.norm(embeddings, axis=1, keepdims=True)
    norms[norms == 0] = 1e-12
    embed_unit = embeddings / norms
    similarities = embed_unit.dot(context_unit)  # (n_songs,)
    cand_idx = np.argsort(-similarities)[:top_n]
    return cand_idx, embeddings[cand_idx]


def compute_direction_vector(history: pd.DataFrame,
                             embeddings: np.ndarray,
                             id2idx: Dict[str, int]) -> np.ndarray:
    """
    Estimate session movement direction as the difference between
    average embedding of first half and second half of recent session.
    Returns a direction vector (unit length). If insufficient data, returns zero.
    """
    if history.empty or len(history) < 2:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    # Use same song ID mapping as before
    if 'matched_msd_id' in history.columns:
        history['song_id'] = history['matched_msd_id'].fillna(history['spotify_id'])
    else:
        history['song_id'] = history['spotify_id']
    recent = history.sort_values('played_at', ascending=False).head(20)
    indices = [id2idx[sid] for sid in recent['song_id'] if sid in id2idx]
    if len(indices) < 2:
        return np.zeros(embeddings.shape[1], dtype=embeddings.dtype)
    seq_embeds = embeddings[indices]   # (n_seq, 64)
    split = len(seq_embeds) // 2
    first_half = seq_embeds[:split]
    second_half = seq_embeds[split:]
    dir_vec = np.mean(second_half, axis=0) - np.mean(first_half, axis=0)
    norm = np.linalg.norm(dir_vec)
    if norm == 0:
        return np.zeros_like(dir_vec)
    return dir_vec / norm


def compute_freshness_score(song_id: str, play_counts: Dict[str, float]) -> float:
    """
    Freshness = 1 / (1 + log1p(play count)). Never played -> 1.
    """
    count = play_counts.get(song_id, 0.0)
    return 1.0 / (1.0 + math.log1p(count))


def compute_similarity_score(song_vec: np.ndarray, context_vec: np.ndarray) -> float:
    """
    Cosine similarity between song vector and context vector.
    """
    a_norm = np.linalg.norm(song_vec)
    b_norm = np.linalg.norm(context_vec)
    if a_norm == 0 or b_norm == 0:
        return 0.0
    return np.dot(song_vec, context_vec) / (a_norm * b_norm)


def compute_direction_alignment_score(song_vec: np.ndarray,
                                      direction_vec: np.ndarray) -> float:
    """
    Alignment = cosine similarity between song vector and direction vector.
    If direction vector is zero, return 0.
    """
    if np.linalg.norm(direction_vec) == 0:
        return 0.0
    a_norm = np.linalg.norm(song_vec)
    d_norm = np.linalg.norm(direction_vec)
    if a_norm == 0 or d_norm == 0:
        return 0.0
    return np.dot(song_vec, direction_vec) / (a_norm * d_norm)


def rank_candidates(candidate_indices: np.ndarray,
                    candidate_vectors: np.ndarray,
                    context_vec: np.ndarray,
                    direction_vec: np.ndarray,
                    play_counts: Dict[str, float],
                    idx2id: Dict[int, str]) -> List[Tuple[str, float, Dict[str, float]]]:
    """
    For each candidate, compute three scores and combine.
    Returns list of tuples: (song_id, combined_score, component_scores)
    """
    scored = []
    for idx, vec in zip(candidate_indices, candidate_vectors):
        song_id = idx2id[int(idx)]
        sim = compute_similarity_score(vec, context_vec)
        dir_al = compute_direction_alignment_score(vec, direction_vec)
        fresh = compute_freshness_score(song_id, play_counts)
        combined = W_SIM * sim + W_DIR * dir_al + W_FRESH * fresh
        scored.append((song_id, combined, {
            'similarity': sim,
            'direction': dir_al,
            'freshness': fresh
        }))
    # Sort by combined score descending
    scored.sort(key=lambda x: x[1], reverse=True)
    return scored


def select_top_10(scored_candidates: List[Tuple[str, float, Dict[str, float]]],
                  play_counts: Dict[str, float]) -> List[Dict]:
    """
    Apply familiarity/discovery balance: aim for 70% familiar, 30% discovery.
    Familiarity defined by play count (higher -> more familiar).
    We'll compute a familiarity score as raw play count.
    Then split candidates into familiar and discovery pools based on a quantile threshold.
    Select top 7 from familiar pool, top 3 from discovery pool (by combined score).
    If a pool lacks enough candidates, fill from the other.
    Returns list of dicts with song_id and component scores.
    """
    if not scored_candidates:
        return []
    # Compute familiarity for each candidate (raw play count)
    familiarity_scores = []
    for song_id, _, _ in scored_candidates:
        count = play_counts.get(song_id, 0.0)
        familiarity_scores.append(float(count))
    familiarity_scores = np.array(familiarity_scores)
    if len(familiarity_scores) == 0:
        threshold = 0
    else:
        threshold = np.quantile(familiarity_scores, FAMILIARITY_THRESHOLD_Q)
    familiar_mask = familiarity_scores >= threshold
    discovery_mask = ~familiar_mask
    familiar_cands = [sc for sc, mask in zip(scored_candidates, familiar_mask) if mask]
    discovery_cands = [sc for sc, mask in zip(scored_candidates, discovery_mask) if mask]
    # Sort each pool by combined score (already sorted overall, but re-sort for safety)
    familiar_cands.sort(key=lambda x: x[1], reverse=True)
    discovery_cands.sort(key=lambda x: x[1], reverse=True)
    # Select up to 7 familiar and 3 discovery
    selected = []
    selected.extend(familiar_cands[:7])
    selected.extend(discovery_cands[:3])
    # If we have less than 10, fill from the remaining candidates in order
    if len(selected) < TOP_FINAL:
        needed = TOP_FINAL - len(selected)
        # Take from the remaining of both pools (excluding already selected)
        selected_ids = {sid for sid, _, _ in selected}
        remaining = [sc for sc in scored_candidates if sc[0] not in selected_ids]
        selected.extend(remaining[:needed])
    # Trim to exactly TOP_FINAL
    selected = selected[:TOP_FINAL]
    # Format output
    results = []
    for song_id, combined, comps in selected:
        results.append({
            'song_id': song_id,
            'combined_score': float(combined),
            'similarity': float(comps['similarity']),
            'direction': float(comps['direction']),
            'freshness': float(comps['freshness'])
        })
    return results


def recommend_songs() -> List[Dict]:
    """
    End-to-end recommendation function that:
    1. Loads embeddings and ID maps.
    2. Loads listening history (from Spotify).
    3. Computes play counts.
    4. Computes long-term user vector U.
    5. Computes session vector S (via Word2Vec or fallback).
    6. Combines to get context C.
    7. Gets direction vector D from session history.
    8. Retrieves top 500 candidates by similarity to C.
    9. For each candidate, computes similarity, direction, freshness scores.
    10. Combines scores with weights.
    11. Selects top 10 with 70/30 familiarity/discovery split.
    Returns list of recommendation dicts.
    """
    # Step 1: Load embeddings
    embeddings, id2idx, idx2id = load_lightfm_embeddings()
    # Step 2: Load listening history
    history = load_listening_history()
    # Step 3: Play counts (raw counts)
    play_counts = get_user_play_counts(history)
    # Step 4: Long-term vector U
    u_vec = get_long_term_user_vector(embeddings, id2idx, play_counts)
    # Step 5: Session vector S
    s_vec = get_session_representation_via_word2vec(history, embeddings, id2idx)
    # Step 6: Combined context C
    c_vec = combine_context(u_vec, s_vec)
    # Step 7: Direction vector D
    d_vec = compute_direction_vector(history, embeddings, id2idx)
    # Step 8: Candidate generation
    cand_idx, cand_vecs = get_candidate_songs(embeddings, c_vec, top_n=TOP_CANDIDATES)
    # Step 9-10: Score and rank candidates
    scored = rank_candidates(cand_idx, cand_vecs, c_vec, d_vec, play_counts, idx2id)
    # Step 11: Select top 10
    top10 = select_top_10(scored, play_counts)
    return top10


